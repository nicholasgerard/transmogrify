/**
 * Emits `dist/_headers` after the Astro build.
 *
 * The Content-Security-Policy carries a SHA-256 hash for every inline <script>
 * the build actually produced, so the policy cannot drift from the output.
 * `'unsafe-inline'` is kept alongside the hashes only for CSP Level 1 browsers:
 * any browser that understands hashes ignores it, so modern clients get the
 * strict policy.
 *
 * Run automatically by `npm run build`. `npm run verify:headers` re-derives the
 * hashes from `dist/` and fails if the emitted file no longer matches.
 */
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const DIST = resolve(process.argv[2] ?? 'dist');

/** Matches inline <script> elements — those with no `src` attribute. */
const SCRIPT_RE = /<script(?![^>]*\ssrc=)([^>]*)>([\s\S]*?)<\/script>/gi;

export async function collectHtmlFiles(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...(await collectHtmlFiles(full)));
    else if (entry.name.endsWith('.html')) found.push(full);
  }
  return found.sort();
}

export function inlineScriptBodies(html) {
  const bodies = [];
  for (const match of html.matchAll(SCRIPT_RE)) {
    bodies.push(match[2]);
  }
  return bodies;
}

export function sha256Source(body) {
  return `'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`;
}

export async function computeScriptHashes(dist) {
  const files = await collectHtmlFiles(dist);
  const hashes = new Set();
  for (const file of files) {
    for (const body of inlineScriptBodies(await readFile(file, 'utf8'))) {
      hashes.add(sha256Source(body));
    }
  }
  return [...hashes].sort();
}

/**
 * `connect-src` and `script-src` list Google's endpoints because the analytics
 * build variant may append the gtag script *after* consent. Listing a host in
 * CSP permits a request; it does not make one. With no measurement ID
 * configured nothing on the page can reach them.
 */
export function renderHeaders(scriptHashes, analyticsConfigured = false) {
  const analyticsScriptSource = analyticsConfigured
    ? ' https://www.googletagmanager.com'
    : '';
  const analyticsConnectSources = analyticsConfigured
    ? ' https://www.google-analytics.com https://region1.google-analytics.com https://analytics.google.com https://www.googletagmanager.com'
    : '';
  const csp = [
    "default-src 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
    `script-src 'self' ${scriptHashes.join(' ')} 'unsafe-inline'${analyticsScriptSource}`,
    // Astro inlines small stylesheets and scoped component CSS. There is no
    // user-supplied content on this site and no injection surface, so inline
    // styles are permitted while scripts are hash-pinned.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    "font-src 'self'",
    `connect-src 'self'${analyticsConnectSources}`,
    "manifest-src 'self'",
    "worker-src 'none'",
    'upgrade-insecure-requests',
  ].join('; ');

  return `# Generated by scripts/build-headers.mjs — do not edit by hand.
# Verify with: npm run verify:headers

/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: accelerometer=(), autoplay=(), camera=(), display-capture=(), encrypted-media=(), fullscreen=(), geolocation=(), gyroscope=(), magnetometer=(), microphone=(), midi=(), payment=(), publickey-credentials-get=(), screen-wake-lock=(), usb=(), xr-spatial-tracking=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  X-Frame-Options: DENY
  Strict-Transport-Security: max-age=31536000; includeSubDomains

# Cloudflare version previews must never compete with the canonical domain.
https://:version.:subdomain.workers.dev/*
  X-Robots-Tag: noindex, nofollow

# Content-hashed build assets only. Everything else must stay revalidatable.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable

/favicon.svg
  Cache-Control: public, max-age=86400
/favicon.ico
  Cache-Control: public, max-age=86400
/apple-touch-icon.png
  Cache-Control: public, max-age=86400
/icon-512.png
  Cache-Control: public, max-age=86400
/og.png
  Cache-Control: public, max-age=86400
/site.webmanifest
  Cache-Control: public, max-age=3600

/start
  Content-Type: text/markdown; charset=utf-8
  Cache-Control: public, max-age=300, must-revalidate
  X-Robots-Tag: noindex
`;
}

if (import.meta.filename === process.argv[1]) {
  const hashes = await computeScriptHashes(DIST);
  const analyticsConfigured = /^G-[A-Z0-9]+$/i.test(
    (process.env.PUBLIC_GA_MEASUREMENT_ID ?? '').trim(),
  );
  const target = join(DIST, '_headers');
  await writeFile(target, renderHeaders(hashes, analyticsConfigured), 'utf8');
  console.log(
    `wrote ${relative(process.cwd(), target)} with ${hashes.length} inline script hash(es)`,
  );
}
